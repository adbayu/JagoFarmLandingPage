const englishToIndonesian = new Map(
  [...idToEnglish].map(([indonesian, english]) => [english, indonesian]),
);

const LanguageContext = createContext("id");

export function LanguageProvider({ language, children }) {
  return <LanguageContext.Provider value={language}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const language = useContext(LanguageContext);
  const translate = (text) => {
    if (typeof text !== "string") return text;
    return (language === "en" ? idToEnglish : englishToIndonesian).get(text) ?? text;
  };

  return { language, t: translate };
}
